"""Stateless model-serving API. Demo only, add authentication before public deployment."""
import os
from functools import lru_cache
from pathlib import Path
import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field
from fraud.features import prepare_features

app = FastAPI(title="Fraud Detection API", version="0.1.0")


class Transaction(BaseModel):
    model_config = ConfigDict(extra="forbid")
    step: int = Field(ge=0)
    type: str = Field(min_length=1, max_length=20)
    amount: float = Field(ge=0, allow_inf_nan=False)
    oldbalanceOrg: float = Field(allow_inf_nan=False)
    newbalanceOrig: float = Field(allow_inf_nan=False)
    oldbalanceDest: float = Field(allow_inf_nan=False)
    newbalanceDest: float = Field(allow_inf_nan=False)


@lru_cache(maxsize=1)
def load_model():
    path = Path(os.getenv("MODEL_PATH", "models/fraud_pipeline.joblib"))
    if not path.is_file():
        raise FileNotFoundError(f"Train model first: {path}")
    return joblib.load(path)  # Only load artifacts generated by your own trusted training job.


@app.get("/health")
def health():
    return {"status": "ok", "model_available": Path(os.getenv("MODEL_PATH", "models/fraud_pipeline.joblib")).is_file()}


@app.post("/predict")
def predict(transaction: Transaction):
    try:
        model = load_model()
    except FileNotFoundError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    score = float(model.predict_proba(prepare_features(pd.DataFrame([transaction.model_dump()])))[:, 1][0])
    threshold = float(os.getenv("FRAUD_THRESHOLD", "0.5"))
    if not 0 < threshold < 1:
        raise HTTPException(500, "FRAUD_THRESHOLD must be between zero and one")
    return {"fraud_probability": round(score, 6), "fraud_flag": score >= threshold, "threshold": threshold, "model_type": "HistGradientBoostingClassifier"}
